-- =====================================================================

DROP TABLE IF EXISTS ref_prediction_band;

CREATE TABLE ref_prediction_band (
    target_kind varchar(4)   NOT NULL,
    item_nm     varchar(20)  NOT NULL,
    lead_biz_d  smallint     NOT NULL,
    ratio_q10   numeric(8,4) NOT NULL,   -- actual/pred 10분위
    ratio_q50   numeric(8,4) NOT NULL,
    ratio_q90   numeric(8,4) NOT NULL,   -- actual/pred 90분위
    PRIMARY KEY (target_kind, item_nm, lead_biz_d)
);

COMMENT ON TABLE ref_prediction_band IS
  '검증 구간 실측 예측구간. pred_lo=pred*ratio_q10, pred_hi=pred*ratio_q90';

